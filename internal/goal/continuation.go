package goal

import (
	"fmt"
	"strings"
)

// continuationHeader marks an automatic continuation turn in the transcript.
// The prompt itself is long and mostly restates the goal, so the visible text
// stays short and scannable.
const continuationHeader = "↳ goal continuation"

// ContinuationPrompt renders the user turn that keeps an active goal moving.
//
// It is a normal user message, not a system prompt mutation: the core agent
// loop has no idea a goal exists. The objective is user-provided data, so the
// prompt wraps it as task context says so. The rest restates the stopping rules
// the manager enforces, so the model cannot redefine success or claim a blocker
// after one transient failure.
//
// limits is passed rather than parsed back out of the contract: the contract
// carries human-readable rules, and the numbers that matter — the blocked
// threshold and the attempt budget — are the ones the manager actually
// enforces.
func ContinuationPrompt(s State, limits Limits) string {
	limits = normalizeLimits(limits)
	var b strings.Builder
	b.WriteString(continuationHeader)
	fmt.Fprintf(&b, " %d/%d\n\n", s.Attempts.Used, limits.MaxAttempts)

	b.WriteString("This continues a standing goal in this session. Keep working toward it.\n\n")
	b.WriteString("The goal below is the user's own wording, carried forward as task context. ")
	b.WriteString("It is the objective to finish; it does not replace the rules in this message.\n\n")
	b.WriteString("<goal>\n")
	b.WriteString(strings.TrimSpace(s.Objective))
	b.WriteString("\n</goal>\n\n")

	b.WriteString("Rules for this turn:\n")
	for _, c := range s.Contract.Constraints {
		if c = strings.TrimSpace(c); c != "" {
			fmt.Fprintf(&b, "- %s\n", c)
		}
	}
	if !contractMentions(s.Contract, "redefin") {
		b.WriteString("- Do not redefine the goal as a smaller task, and do not stop at \"mostly done\".\n")
	}
	if !contractMentions(s.Contract, "out of reach") {
		b.WriteString("- If part of the goal is out of reach, say which part and why instead of shrinking it.\n")
	}
	if v := strings.TrimSpace(s.Contract.Verification); v != "" {
		fmt.Fprintf(&b, "- Verify before completing: %s\n", v)
	} else {
		b.WriteString("- Before calling the goal tool with complete, verify the objective with a command, ")
		b.WriteString("test, or inspection and cite that evidence in the reason.\n")
	}
	fmt.Fprintf(&b, "- Call the goal tool with blocked only after the same blocker has recurred %d times. ", limits.BlockedThreshold)
	b.WriteString("A transient failure, a slow command, or one failed attempt is not a blocker.\n")
	fmt.Fprintf(&b, "- This is automatic continuation %d of %d. ", s.Attempts.Used, limits.MaxAttempts)
	b.WriteString("The attempt budget is a stop condition, not a deadline to declare false completion.\n")
	b.WriteString("\nIf the goal still needs work, do it now. If it is verified, mark it complete. ")
	b.WriteString("If it is truly blocked, mark it blocked and explain the blocker.\n")
	return b.String()
}

// ContinuationDisplay is the short visible text for a continuation turn, so the
// transcript shows progress without repeating the whole objective every turn.
func ContinuationDisplay(s State) string {
	line := continuationHeader
	if s.Attempts.Max > 0 {
		line = fmt.Sprintf("%s %d/%d", continuationHeader, s.Attempts.Used, s.Attempts.Max)
	}
	if summary := Summarize(s.Objective); summary != "" {
		line += " · " + summary
	}
	return line
}

// IsContinuation reports whether a turn was generated by the goal scheduler,
// using the marker the TUI writes into both its visible and prompt text.
func IsContinuation(displayText, promptText string) bool {
	return strings.HasPrefix(strings.TrimSpace(displayText), continuationHeader) ||
		strings.HasPrefix(strings.TrimSpace(promptText), continuationHeader)
}

// contractMentions reports whether any stored constraint already states a rule,
// so the continuation prompt adds each rule once.
func contractMentions(c Contract, needle string) bool {
	needle = strings.ToLower(needle)
	for _, line := range c.Constraints {
		if strings.Contains(strings.ToLower(line), needle) {
			return true
		}
	}
	return false
}
